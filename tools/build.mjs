// Builds the site's data from the markdown in content/:
//   content/releases/*.md  ->  data/releases.js   (window.RELEASES)
//   content/garden/*.md    ->  data/garden.js     (window.GARDEN)
//   content/notes/*.md     ->  data/notes.js      (window.NOTES) and feed.xml
// Run it after editing anything in content/:  npm run build   (or: node tools/build.mjs)
// Each file is YAML front matter between --- lines, then the text. Files starting with _ are not items.
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import YAML from "yaml";
import { marked } from "marked";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SITE = "https://glassgarden.cc";

function parse(raw, label) {
  const m = raw.replace(/\r\n/g, "\n").match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!m) throw new Error(`${label}: missing front matter`);
  return { data: YAML.parse(m[1]) || {}, text: m[2].trim() };
}

function readDir(name) {
  const dir = join(root, "content", name);
  return readdirSync(dir)
    .filter((f) => f.endsWith(".md") && !f.startsWith("_"))
    .sort()
    .map((f) => parse(readFileSync(join(dir, f), "utf8"), `content/${name}/${f}`));
}

// Plain text, paragraphs joined: for the short summaries (shown as text, not HTML).
const plain = (t) => t.split(/\n\s*\n/).map((p) => p.replace(/\s*\n\s*/g, " ").trim()).filter(Boolean).join(" ");
// Markdown paragraphs to inline HTML strings (raw HTML passes through untouched).
const paras = (t) => t.split(/\n\s*\n/).map((p) => p.trim()).filter(Boolean).map((p) => marked.parseInline(p).replace(/&#39;/g, "'").replace(/&quot;/g, "\""));
const byOrder = (a, b) => (a.order ?? 1e9) - (b.order ?? 1e9);
const write = (file, header, name, value) =>
  writeFileSync(
    join(root, file),
    `/* ${header} Generated by tools/build.mjs from content/: edit the markdown there, not this file. */\nwindow.${name} = ${JSON.stringify(value, null, 2)};\n`,
  );

// releases: front matter + body = summary
const releases = readDir("releases")
  .map(({ data, text }) => ({ ...data, summary: plain(text) }))
  .sort(byOrder)
  .map(({ order, ...r }) => r);
write("data/releases.js", "Releases, newest first.", "RELEASES", releases);

// garden: front matter + body = summary; _garden.md holds `tended`
const meta = parse(readFileSync(join(root, "content/garden/_garden.md"), "utf8"), "_garden.md").data;
const items = readDir("garden")
  .map(({ data, text }) => ({ ...data, ...(text ? { summary: plain(text) } : {}) }))
  .sort(byOrder)
  .map(({ order, ...i }) => i);
write("data/garden.js", "The garden, by stage.", "GARDEN", { tended: meta.tended, items });

// notes: body is markdown; a line with <!-- widget --> splits the text before and after the widget.
// Drafts (draft: true) are left out of the output entirely, so they never reach the public site.
const notes = readDir("notes")
  .filter(({ data }) => !data.draft)
  .map(({ data, text }) => {
    const [before, after] = text.split(/^<!--\s*widget\s*-->\s*$/m);
    return { ...data, body: paras(before), ...(after !== undefined ? { after: paras(after) } : {}) };
  })
  .sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : byOrder(a, b)))
  .map(({ order, ...n }) => n);
write("data/notes.js", "Notes, newest first.", "NOTES", notes);

// feed.xml
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const abs = (html) => html.replace(/(href|src)="\//g, `$1="${SITE}/`);
const date = (d) => new Date(d + "T12:00:00Z").toUTCString();

function content(n) {
  const parts = [];
  if (n.photo) parts.push(`<p><img src="${SITE}${n.photo.src}" alt="${esc(n.photo.alt || "")}"></p>`);
  (n.body || []).forEach((p) => parts.push(`<p>${abs(p)}</p>`));
  if (n.widget) parts.push(`<p><a href="${SITE}/notes.html#${n.slug}">There's something to play in this note: open it on the site.</a></p>`);
  (n.after || []).forEach((p) => parts.push(`<p>${abs(p)}</p>`));
  if (n.links && n.links.length) {
    const url = (u) => (u.startsWith("/") ? SITE + u : u);
    parts.push("<p>" + n.links.map((l) => `<a href="${esc(url(l.url))}">${esc(l.label)}</a>`).join(" · ") + "</p>");
  }
  return parts.join("\n").replace(/]]>/g, "]]&gt;");
}

const feedItems = notes.map((n) => `    <item>
      <title>${esc(n.title)}</title>
      <link>${SITE}/notes.html#${n.slug}</link>
      <guid isPermaLink="false">glassgarden-note-${n.slug}</guid>
      <pubDate>${date(n.date)}</pubDate>${n.tag ? `\n      <category>${esc(n.tag)}</category>` : ""}
      <description><![CDATA[${content(n)}]]></description>
    </item>`);

const xml = `<?xml version="1.0" encoding="utf-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
  <channel>
    <title>glassgarden notes</title>
    <link>${SITE}/notes.html</link>
    <atom:link href="${SITE}/feed.xml" rel="self" type="application/rss+xml"/>
    <description>Field notes from glassgarden: generative ambient music, grown in small sealed worlds.</description>
    <language>en</language>
    <lastBuildDate>${notes.length ? date(notes[0].date) : new Date().toUTCString()}</lastBuildDate>
${feedItems.join("\n")}
  </channel>
</rss>
`;
writeFileSync(join(root, "feed.xml"), xml);
console.log(`built: ${releases.length} releases, ${items.length} garden items, ${notes.length} notes (feed.xml)`);
